function wrapNavLinkChars() {
  document.querySelectorAll('.nav-links a[data-i18n]').forEach(link => {
    const text = (link.textContent || '').trim();
    if (!text) return;
    if (link.dataset.wrapped === text) return;
    link.dataset.wrapped = text;
    link.innerHTML = [...text].map((ch, i) =>
      `<span class="nav-char" style="--ci:${i}">${ch === ' ' ? '\u00a0' : ch}</span>`
    ).join('');
  });
}

function toggleCard(card) {
  const isExpanded = card.classList.contains('expanded');
  document.querySelectorAll('.menu-card.expanded').forEach(c => c.classList.remove('expanded'));
  if (!isExpanded) card.classList.add('expanded');
}

function toggleTheme() {
  currentTheme = currentTheme === 'light' ? 'dark' : 'light';
  document.documentElement.setAttribute('data-theme', currentTheme === 'dark' ? 'dark' : '');
}

