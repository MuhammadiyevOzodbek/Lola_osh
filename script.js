function detectLang() {
  const nav = navigator.language || navigator.userLanguage || 'en';
  const code = nav.slice(0, 2).toLowerCase();
  if (code === 'ru') return 'ru';
  if (code === 'uz') return 'uz';
  return 'en';
}

